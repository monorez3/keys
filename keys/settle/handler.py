"""Ключ «кто кому сколько должен»: расходы компании -> минимум переводов.

Ядро вырезано из Tally. Смысл в двух шагах:

    1. баланс каждого = сколько он заплатил минус его доля в общих тратах;
    2. гасим самый большой долг самым большим кредитом, пока долгов не станет.

Второй шаг и даёт выигрыш: при наивном «каждый должник платит каждому
кредитору» переводов было бы должники × кредиторы, а тут — почти всегда
должники + кредиторы − 1.

Сети тут нет вообще, только счёт. Поэтому ключ отвечает мгновенно, не тратит
наружный бюджет и кэшируется надолго: на одних и тех же расходах ответ один.
"""

from __future__ import annotations

import re

ЦЕНТ = 0.009  # мельче — уже не долг, а ошибка округления


def _число(текст: str, где: str) -> float:
    значение = текст.strip().replace(",", ".").replace(" ", "")
    if not значение:
        raise ValueError(f"в записи «{где}» не указана сумма")
    try:
        сумма = float(значение)
    except ValueError:
        raise ValueError(f"в записи «{где}» сумма «{текст.strip()}» — не число") from None
    if сумма < 0:
        raise ValueError(f"в записи «{где}» сумма отрицательная")
    return сумма


def разобрать(строка: str) -> list[dict]:
    """'аня:1200:аня,боря; боря:600' -> список трат.

    Разделители намеренно разные: точка с запятой отделяет записи, двоеточие —
    поля, запятая — участников. Так строку можно писать в одну строку руками и
    не путаться.
    """
    if not (строка or "").strip():
        raise ValueError("пустой список расходов")

    записи = []
    for кусок in re.split(r"[;\n]+", строка):
        кусок = кусок.strip()
        if not кусок:
            continue
        поля = [ч.strip() for ч in кусок.split(":")]
        if len(поля) < 2:
            raise ValueError(f"в записи «{кусок}» не хватает суммы: нужно кто:сколько")
        if len(поля) > 3:
            raise ValueError(f"в записи «{кусок}» слишком много двоеточий")

        плательщик = поля[0]
        if not плательщик:
            raise ValueError(f"в записи «{кусок}» не указано, кто платил")
        участники = [ч.strip() for ч in поля[2].split(",") if ч.strip()] if len(поля) == 3 else []
        записи.append({
            "кто": плательщик,
            "сколько": _число(поля[1], кусок),
            "на кого": участники,
        })
    if not записи:
        raise ValueError("пустой список расходов")
    return записи


def балансы(записи: list[dict]) -> dict[str, float]:
    """Чистый баланс каждого: >0 — ему должны, <0 — он должен."""
    все = []
    for з in записи:
        for имя in [з["кто"], *з["на кого"]]:
            if имя not in все:
                все.append(имя)

    баланс = {имя: 0.0 for имя in все}
    for з in записи:
        делят = з["на кого"] or все
        if not делят:
            continue
        доля = з["сколько"] / len(делят)
        баланс[з["кто"]] += з["сколько"]
        for имя in делят:
            баланс[имя] -= доля
    return {имя: round(v, 2) for имя, v in баланс.items()}


def план(баланс: dict[str, float]) -> list[tuple[str, str, float]]:
    """Жадно гасим самый большой долг самым большим кредитом."""
    долги = sorted([[и, -v] for и, v in баланс.items() if v < -ЦЕНТ], key=lambda x: -x[1])
    кредиты = sorted([[и, v] for и, v in баланс.items() if v > ЦЕНТ], key=lambda x: -x[1])

    переводы, i, j = [], 0, 0
    while i < len(долги) and j < len(кредиты):
        платёж = min(долги[i][1], кредиты[j][1])
        переводы.append((долги[i][0], кредиты[j][0], round(платёж, 2)))
        долги[i][1] -= платёж
        кредиты[j][1] -= платёж
        if долги[i][1] < 0.01:
            i += 1
        if кредиты[j][1] < 0.01:
            j += 1
    return переводы


def _деньги(v: float) -> str:
    return f"{v:.2f}".rstrip("0").rstrip(".")


def посчитать(строка: str) -> dict:
    """Чистая функция: строка расходов -> ответ ключа. Ни сети, ни состояния."""
    записи = разобрать(строка)
    баланс = балансы(записи)
    переводы = план(баланс)

    должников = sum(1 for v in баланс.values() if v < -ЦЕНТ)
    кредиторов = sum(1 for v in баланс.values() if v > ЦЕНТ)

    return {
        "ok": True,
        "transfers": " · ".join(f"{кто} → {кому} {_деньги(с)}" for кто, кому, с in переводы)
                     or "никто никому ничего не должен",
        "transfers_count": len(переводы),
        "naive_count": должников * кредиторов,
        "balances": " · ".join(
            f"{имя} {'+' if v > 0 else ''}{_деньги(v)}"
            for имя, v in sorted(баланс.items(), key=lambda x: -x[1])
        ),
        "total": round(sum(з["сколько"] for з in записи), 2),
        "people": len(баланс),
    }


def canonical(params: dict) -> dict:
    """Одни и те же расходы, записанные с разными пробелами, — один ключ кэша.

    Имя параметра латиницей намеренно: кириллическое имя в адресной строке
    приходится кодировать, и половина инструментов (тот же curl) молча
    ломается. Значение при этом какое угодно — это же имена людей.
    """
    записи = разобрать(params.get("expenses", ""))
    строки = sorted(
        f"{з['кто']}:{з['сколько']:g}:{','.join(sorted(з['на кого']))}" for з in записи
    )
    return params | {"expenses": ";".join(строки)}


async def run(params: dict, ctx) -> dict:
    return посчитать(params["expenses"])
